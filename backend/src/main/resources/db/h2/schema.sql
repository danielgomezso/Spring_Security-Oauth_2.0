-- La URL JDBC crea citasdb en memoria. Este script crea todas las tablas.
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 rol VARCHAR(20) NOT NULL CHECK (rol IN ('ROLE_USER','ROLE_ADMIN'))
);
CREATE TABLE IF NOT EXISTS citas_medicas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 medico_nombre VARCHAR(100) NOT NULL,
 fecha DATE NOT NULL,
 hora TIME NOT NULL,
 motivo VARCHAR(500) NOT NULL,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA')),
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 CONSTRAINT uk_medico_horario UNIQUE (medico_nombre, fecha, hora)
);
CREATE INDEX IF NOT EXISTS idx_citas_usuario ON citas_medicas(usuario_id);
